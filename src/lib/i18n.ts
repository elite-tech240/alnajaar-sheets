export const langs: Lang[] = ["ar", "en"];
export const isLang = (v: string): v is Lang => v === "ar" || v === "en";
export const dirOf = (lang: Lang) => (lang === "ar" ? "rtl" : "ltr");

export function formatPrice(value: number, lang: Lang): string {
  const n = new Intl.NumberFormat(lang === "ar" ? "ar-EG" : "en-EG", { maximumFractionDigits: 2 }).format(value);
  return lang === "ar" ? `${n} ج.م` : `${n} EGP`;
}

